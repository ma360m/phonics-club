function redirect(source, destination, category, reason, extra = {}) {
  return {
    source,
    destination,
    permanent: true,
    category,
    reason,
    ...extra,
  }
}

function withHtml(source, destination, category, reason) {
  return [
    redirect(source, destination, category, reason),
    redirect(`${source}.html`, destination, category, `${reason}; handles old .html URL variant`),
  ]
}

function withChildren(source, destination, category, reason) {
  return [
    redirect(source, destination, category, reason),
    redirect(`${source}/:path*`, destination, category, `${reason}; collapses old WordPress child paths`),
  ]
}

function queryRedirect(key, value, destination, category, reason, extraHas = []) {
  return redirect(
    '/',
    destination,
    category,
    reason,
    {
      has: [
        { type: 'query', key, value },
        ...extraHas,
      ],
    },
  )
}

