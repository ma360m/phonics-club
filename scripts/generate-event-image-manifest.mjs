import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')
const outputFile = path.join(projectRoot, 'lib', 'data', 'event-image-manifest.ts')
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif'])

const roots = [
  { key: 'photos', publicRoot: '/images/photos', folder: path.join(projectRoot, 'public', 'images', 'photos') },
  { key: 'blog', publicRoot: '/images/blog', folder: path.join(projectRoot, 'public', 'images', 'blog') },
]

function publicImagePath(root, folder, file) {
  return [
    root,
    ...folder.split(/[\\/]+/).filter(Boolean).map((part) => encodeURIComponent(part)),
    ...file.split(/[\\/]+/).filter(Boolean).map((part) => encodeURIComponent(part)),
  ].join('/')
}

async function listImageFilesRecursive(folder, baseFolder = folder) {
  let entries
  try {
    entries = await readdir(folder, { withFileTypes: true })
  } catch {
    return []
  }

  const files = await Promise.all(entries.map(async (entry) => {
    const entryPath = path.join(folder, entry.name)
    if (entry.isDirectory()) return listImageFilesRecursive(entryPath, baseFolder)
    if (!entry.isFile() || !imageExtensions.has(path.extname(entry.name).toLowerCase())) return []
    return [path.relative(baseFolder, entryPath)]
  }))

  return files.flat()
}

function imageAlt(folder, index) {
  return `${folder.replace(/[-_/\\]+/g, ' ')} event photograph ${index + 1}`
}

const manifest = {}

for (const root of roots) {
  let folders = []
  try {
    folders = await readdir(root.folder, { withFileTypes: true })
  } catch {
    folders = []
  }

  for (const folderEntry of folders) {
    if (!folderEntry.isDirectory()) continue
    const folder = folderEntry.name
    const absoluteFolder = path.join(root.folder, folder)
    const files = (await listImageFilesRecursive(absoluteFolder))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))

    if (!files.length) continue

    manifest[`${root.key}/${folder}`] = files.map((file, index) => ({
      src: publicImagePath(root.publicRoot, folder, file),
      alt: imageAlt(folder, index),
      caption: null,
    }))
  }
}

const file = `import type { BlogGalleryImage } from '@/types/database'

// Generated by scripts/generate-event-image-manifest.mjs. Do not edit by hand.
export const EVENT_IMAGE_MANIFEST: Record<string, BlogGalleryImage[]> = ${JSON.stringify(manifest, null, 2)}
`

let current = ''
try {
  current = await readFile(outputFile, 'utf8')
} catch {
  current = ''
}

if (current !== file) {
  await writeFile(outputFile, file)
}
